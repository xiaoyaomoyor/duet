/**
 * 音频模块的类型定义（见 text/data.ts 顶部关于循环依赖的说明）
 */

export interface AudioProps {
  /** 波形展示（M4 接入真实波形数据；M2 显示占位律动） */
  showWaveform: boolean
  /** 是否上报播放时间（供歌词/进度条联动） */
  reportClock: boolean
  /**
   * 是否显示封面（M7）。
   *
   * 封面来自音频文件**内嵌**的图片（mp3 的 ID3 APIC），导入时被抽出来
   * 存成一张独立的图片资源。它是"顺带捡到的"信息，不是用户主动选的，
   * 因此必须能关掉：有些对比场景下，两张大小不一的专辑封面会把
   * 左右两栏的头部撑得不一样高，反而破坏对齐。
   *
   * 关掉之后**不留空位**；开着但没有内嵌封面时显示音乐图标占位，
   * 这样左右两栏的头部结构仍然一致。
   */
  showCover: boolean
  /**
   * 是否显示自定义播放条（M9）。
   *
   * 这一条**取代了浏览器原生的 `<audio controls>`**：
   * 原生控件那一条的已播放部分是浏览器用固定色画的，改不了颜色，
   * 与"用工具强调色"的诉求直接冲突，也没法单独隐藏。
   * 换成一排自研控件之后，配色、隐藏、尺寸都归我们管。
   *
   * 关掉它音频仍然能播——播放由「音频控制台」或歌词/进度条联动驱动，
   * 只是这个模块自己不再提供一排控件。
   */
  showPlayer: boolean
  /**
   * 布局（v0.4.5）。
   *
   *   bar    长条：封面在左，右侧自上而下是名称、波形、播放条（时间在播放条右侧）
   *   square 正方形：封面铺满整个方块作背景，名称/波形/播放器叠在它上面
   *
   * 两种布局共用同一份内容，只是摆放方式不同——所以做成一个选项，
   * 而不是两个模块。
   */
  layout: AudioLayout
}

export type AudioLayout = 'bar' | 'square'

/**
 * 音频模块的数据（v0.5.0 起可以覆盖封面）。
 *
 * 覆盖而不是替换内嵌封面：内嵌那张是"文件自带的"，传上来的这张是
 * "用户想要的那张"。用户既然特意传了一张，就不该被文件里的旧图盖掉；
 * 清空这个字段即回到内嵌封面——两条信息都留着，切换是免费的。
 */
export interface AudioData {
  coverAssetId?: string | undefined
}
